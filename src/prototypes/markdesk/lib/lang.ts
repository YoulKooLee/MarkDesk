const PACKS: Record<LangCode, Pack> = {
  'zh-CN': zhCN, 'zh-TW': zhTW, en, ja, ko, es, fr, de, ru, pt,
};

/**
 * 取词：当前语言 → 缺项回落简体中文 → 仍无则返回键名（SRS 3.5.6.5 边界）。
 */
export function translate(lang: LangCode, key: UiKey, vars?: Record<string, string | number>): string {
  let value = PACKS[lang]?.[key] ?? zhCN[key] ?? key;
  if (vars) {
    for (const [name, raw] of Object.entries(vars)) {
      value = value.split(`{${name}}`).join(String(raw));
    }
  }
  return value;
}
